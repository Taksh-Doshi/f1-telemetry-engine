-- Core star-schema tables. Lap records remain raw here, with cleaning in SQL views.

CREATE TABLE IF NOT EXISTS events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    season_year SMALLINT NOT NULL,
    round_number SMALLINT NOT NULL,
    event_name TEXT NOT NULL,
    official_event_name TEXT,
    country TEXT,
    location TEXT,
    event_format TEXT,
    event_date DATE,
    CONSTRAINT pk_events PRIMARY KEY (event_id),
    CONSTRAINT uq_events_season_round UNIQUE (season_year, round_number),
    CONSTRAINT ck_events_season_year_positive CHECK (season_year > 0),
    CONSTRAINT ck_events_round_positive CHECK (round_number > 0)
);

CREATE TABLE IF NOT EXISTS sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id BIGINT NOT NULL,
    session_name TEXT NOT NULL,
    session_type VARCHAR(8) NOT NULL,
    start_time TIMESTAMPTZ,
    end_time TIMESTAMPTZ,
    CONSTRAINT pk_sessions PRIMARY KEY (session_id),
    CONSTRAINT fk_sessions_event FOREIGN KEY (event_id)
        REFERENCES events (event_id) ON DELETE CASCADE,
    CONSTRAINT uq_sessions_event_type UNIQUE (event_id, session_type),
    CONSTRAINT ck_sessions_end_after_start
        CHECK (start_time IS NULL OR end_time IS NULL OR end_time >= start_time)
);

CREATE TABLE IF NOT EXISTS drivers (
    driver_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    abbreviation VARCHAR(3) NOT NULL,
    driver_number VARCHAR(3),
    first_name TEXT,
    last_name TEXT,
    full_name TEXT,
    country_code VARCHAR(3),
    CONSTRAINT pk_drivers PRIMARY KEY (driver_id),
    CONSTRAINT uq_drivers_abbreviation UNIQUE (abbreviation),
    CONSTRAINT ck_drivers_abbreviation_not_empty CHECK (length(abbreviation) > 0)
);

CREATE TABLE IF NOT EXISTS laps (
    lap_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    session_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    lap_number SMALLINT NOT NULL,
    lap_time_seconds DOUBLE PRECISION,
    sector1_seconds DOUBLE PRECISION,
    sector2_seconds DOUBLE PRECISION,
    sector3_seconds DOUBLE PRECISION,
    speed_i1 DOUBLE PRECISION,
    speed_i2 DOUBLE PRECISION,
    speed_fl DOUBLE PRECISION,
    speed_st DOUBLE PRECISION,
    compound TEXT,
    tyre_life SMALLINT,
    fresh_tyre BOOLEAN,
    stint_number SMALLINT,
    position SMALLINT,
    track_status TEXT,
    is_personal_best BOOLEAN,
    is_accurate BOOLEAN,
    deleted BOOLEAN,
    deleted_reason TEXT,
    pit_in_time_seconds DOUBLE PRECISION,
    pit_out_time_seconds DOUBLE PRECISION,
    CONSTRAINT pk_laps PRIMARY KEY (lap_id),
    CONSTRAINT fk_laps_session FOREIGN KEY (session_id)
        REFERENCES sessions (session_id) ON DELETE CASCADE,
    CONSTRAINT fk_laps_driver FOREIGN KEY (driver_id)
        REFERENCES drivers (driver_id),
    CONSTRAINT uq_laps_session_driver_lap UNIQUE (session_id, driver_id, lap_number),
    CONSTRAINT ck_laps_number_positive CHECK (lap_number > 0)
);

CREATE TABLE IF NOT EXISTS stints (
    stint_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    session_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    stint_number SMALLINT NOT NULL,
    start_lap SMALLINT NOT NULL,
    end_lap SMALLINT,
    compound TEXT,
    tyre_age_at_start SMALLINT,
    fresh_tyre BOOLEAN,
    CONSTRAINT pk_stints PRIMARY KEY (stint_id),
    CONSTRAINT fk_stints_session FOREIGN KEY (session_id)
        REFERENCES sessions (session_id) ON DELETE CASCADE,
    CONSTRAINT fk_stints_driver FOREIGN KEY (driver_id)
        REFERENCES drivers (driver_id),
    CONSTRAINT uq_stints_session_driver_number
        UNIQUE (session_id, driver_id, stint_number),
    CONSTRAINT ck_stints_number_positive CHECK (stint_number > 0),
    CONSTRAINT ck_stints_start_lap_positive CHECK (start_lap > 0),
    CONSTRAINT ck_stints_end_after_start
        CHECK (end_lap IS NULL OR end_lap >= start_lap)
);

CREATE TABLE IF NOT EXISTS weather (
    weather_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    session_id BIGINT NOT NULL,
    time_seconds DOUBLE PRECISION NOT NULL,
    air_temp DOUBLE PRECISION,
    track_temp DOUBLE PRECISION,
    humidity DOUBLE PRECISION,
    pressure DOUBLE PRECISION,
    rainfall BOOLEAN,
    wind_direction SMALLINT,
    wind_speed DOUBLE PRECISION,
    CONSTRAINT pk_weather PRIMARY KEY (weather_id),
    CONSTRAINT fk_weather_session FOREIGN KEY (session_id)
        REFERENCES sessions (session_id) ON DELETE CASCADE,
    CONSTRAINT uq_weather_session_time UNIQUE (session_id, time_seconds)
);

-- PostgreSQL does not automatically index the referencing side of foreign keys.
CREATE INDEX IF NOT EXISTS idx_sessions_event_id ON sessions (event_id);
CREATE INDEX IF NOT EXISTS idx_laps_session_id ON laps (session_id);
CREATE INDEX IF NOT EXISTS idx_laps_driver_id ON laps (driver_id);
CREATE INDEX IF NOT EXISTS idx_stints_session_id ON stints (session_id);
CREATE INDEX IF NOT EXISTS idx_stints_driver_id ON stints (driver_id);
CREATE INDEX IF NOT EXISTS idx_weather_session_id ON weather (session_id);
